// lib/fix.mjs — `mc scan --fix`: generate a governance scaffold that governs the
// flagged capabilities with @makerchecker/embedded primitives.
//
// The scaffold encodes the MakerChecker thesis directly: deny-by-default, every
// high-risk skill held by a SEPARATE approver role (so the agent structurally
// cannot approve its own dangerous call), and each composition pair turned into a
// role conflict so no single role holds both halves of an exfil/RCE/drain channel.
//
// This writes a NEW file; it never edits the user's code. Zero deps.

const IDENT_RE = /[^A-Za-z0-9_$]/g;

function ident(name) {
  let s = String(name).replace(IDENT_RE, '_');
  if (/^[0-9]/.test(s)) s = `_${s}`;
  return s || '_tool';
}

function skillRef(name) {
  const clean = String(name).trim().replace(/[^\w.-]/g, '_');
  return `${clean || 'tool'}@1`;
}

const isHigh = (f) => f.severity === 'CATASTROPHIC' || f.severity === 'HIGH';

/**
 * Build a runnable @makerchecker/embedded governance scaffold for the flagged
 * findings. Returns the file text, or null when there is nothing to govern.
 * @param {import('./classify.mjs').Finding[]} findings
 * @param {import('./compose.mjs').Pair[]} [pairs]
 * @returns {string|null}
 */
export function generateFixScaffold(findings, pairs = []) {
  const flagged = [];
  const seen = new Set();
  for (const f of Array.isArray(findings) ? findings : []) {
    if (!f || !f.tool || !f.tool.name) continue;
    if (f.governedBy || f.severity === 'OK' || f.unverified) continue;
    if (seen.has(f.tool.name)) continue;
    seen.add(f.tool.name);
    flagged.push(f);
  }
  if (!flagged.length) return null;

  const L = [];
  L.push('// mc-governance.mjs — generated by `mc scan --fix`.');
  L.push('//');
  L.push('// Governs the capabilities mc scan flagged, using @makerchecker/embedded:');
  L.push('// deny-by-default, every high-risk skill held by a SEPARATE approver role, and');
  L.push('// each composition pair enforced as a role conflict (no role holds both halves).');
  L.push('//');
  L.push('//   1. npm i @makerchecker/embedded');
  L.push('//   2. Replace each executor placeholder with your real tool.');
  L.push('//   3. Call the governed wrappers instead of the raw tools.');
  L.push("import { createGovernor, GovernanceDeniedError } from '@makerchecker/embedded';");
  L.push('');
  L.push('export const gov = createGovernor();');
  L.push('');
  L.push('gov');
  for (const f of flagged) {
    const ref = skillRef(f.tool.name);
    if (isHigh(f)) L.push(`  .defineSkill('${ref}', { riskTier: 'high' })  // ${f.severity}: ${f.action || f.signature || 'flagged'}`);
    else L.push(`  .defineSkill('${ref}')  // ${f.severity}`);
  }
  L.push("  .defineRole('agent')       // your autonomous agent: reads and proposes");
  L.push("  .defineRole('risk-desk')   // a SEPARATE party that holds the high-risk skills");
  for (const f of flagged) {
    const ref = skillRef(f.tool.name);
    L.push(`  .grant('${isHigh(f) ? 'risk-desk' : 'agent'}', '${ref}')`);
  }
  const conflictSeen = new Set();
  for (const p of Array.isArray(pairs) ? pairs : []) {
    const a = skillRef(p.tools?.[0]);
    const b = skillRef(p.tools?.[1]);
    const key = [a, b].sort().join('|');
    if (!p.tools?.[0] || !p.tools?.[1] || a === b || conflictSeen.has(key)) continue;
    conflictSeen.add(key);
    L.push(`  .defineConflict('${a}', '${b}')  // ${p.rule}: one role must never hold both`);
  }
  L.push("  .defineAgent('my-agent', 'agent')");
  L.push("  .defineAgent('approver', 'risk-desk');");
  L.push('');
  L.push('// Governed wrappers. A high-risk skill is granted to `risk-desk`, NOT to the agent,');
  L.push('// so calling it as `my-agent` is denied before any side effect (skill_not_granted)');
  L.push('// — the agent cannot grant itself the skill. A high-risk call by the approver still');
  L.push('// needs a preceding gate: pass { hasSeparationGate: true } once a separate party has');
  L.push('// signed. GovernanceDeniedError is thrown on any deny.');
  for (const f of flagged) {
    const ref = skillRef(f.tool.name);
    const varName = ident(f.tool.name);
    const agent = isHigh(f) ? 'approver' : 'my-agent';
    L.push(`export const ${varName} = gov.governedTool('${agent}', '${ref}', async (input) => {`);
    L.push(`  throw new Error('${f.tool.name}: replace this executor with your real tool');`);
    L.push('});');
  }
  L.push('');
  L.push('export { GovernanceDeniedError };');
  L.push('');
  return L.join('\n');
}
